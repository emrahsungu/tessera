            _w.Line($"public {name}(ref byte v) => _v = ref v;");
            _w.Line();
            _w.Line("/// <summary>Whether the list is absent: it was null when written.</summary>");
            _w.Line("public bool IsNull => TesseraReader.IsAbsent(in _v);");
            _w.Line();
            _w.Line("/// <summary>How many items the list has.</summary>");
            _w.Line("public int Count => (int)Unsafe.ReadUnaligned<uint>(ref _v);");
