using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Tessera.Generator
{
    /// <summary>
    /// Emits the C# read types: for each class a <c>ref struct</c> named after it (<c>MonsterView</c> for <c>Monster</c>)
    /// that reads its fields where they are stored in a buffer, and the lists, dictionaries and abstract-class values those
    /// return. Field positions are computed from the header bits with constants, as in the C++ headers.
    /// </summary>
    internal sealed class CSharpViewEmitter
    {
        private readonly List<TypeModel> _types;
        private readonly string _ns;   // the generated namespace: helpers, and read types of other assemblies' classes
        private readonly Compilation _compilation;
        private readonly CodeWriter _w = new CodeWriter();

        private readonly Dictionary<TypeModel, Placed> _placed = new Dictionary<TypeModel, Placed>();  // objects, unions, dictionaries, vectors
        private readonly HashSet<string> _taken = new HashSet<string>(StringComparer.Ordinal);
        private readonly Dictionary<string, List<Action>> _byNamespace = new Dictionary<string, List<Action>>(StringComparer.Ordinal);
        private readonly List<string> _accessors = new List<string>();
        private readonly HashSet<StructModel> _structReaders = new HashSet<StructModel>();

        private sealed class Placed
        {
            public string Ns = "";
            public string Name = "";
            public bool Public;
            public string Full => "global::" + (Ns.Length > 0 ? Ns + "." : "") + Name;
        }

        public CSharpViewEmitter(List<TypeModel> types, string generatedNamespace, Compilation compilation)
        {
            _types = types;
            _ns = generatedNamespace;
            _compilation = compilation;
        }

        public string Emit()
        {
            // Names first (deterministic: the types' order), so read types can refer to each other.
            foreach (var t in _types)
            {
                if (t is ObjectModel o && o.Map == null) Place(t, NamespaceOf(o.Symbol), BaseName(o.Symbol) + "View", IsPublic(o.Symbol));
            }

            // A base class or interface declared with all its derived types gets the plain name; a field restricted to some of
            // them ([TesseraUnion]) gets a name that lists them.
            foreach (var group in _types.OfType<UnionModel>().GroupBy(u => u.Symbol, SymbolEqualityComparer.Default))
            {
                int most = group.Max(u => u.Members.Count);
                foreach (var u in group.OrderByDescending(u => u.Members.Count))
                {
                    string name = u.Members.Count == most && !_placed.Keys.OfType<UnionModel>().Any(x => SymbolEqualityComparer.Default.Equals(x.Symbol, u.Symbol))
                        ? BaseName(u.Symbol) + "View"
                        : BaseName(u.Symbol) + "Of" + string.Concat(u.Members.OrderBy(m => m.Tag).Select(m => BaseName(m.Type.Symbol))) + "View";
                    Place(u, NamespaceOf(u.Symbol), name, IsPublic(u.Symbol));
                }
            }

            foreach (var t in _types)
            {
                if (t is ObjectModel { Map: not null } || (t is VectorModel v && GeneratedList(v))) P(t);
            }

            foreach (var t in _types)
            {
                switch (t)
                {
                    case ObjectModel o when o.Map == null: Add(P(o).Ns, () => EmitObject(o)); break;
                    case ObjectModel o: Add(P(o).Ns, () => EmitMap(o)); break;
                    case UnionModel u: Add(P(u).Ns, () => EmitUnion(u)); break;
                    case VectorModel v when GeneratedList(v): Add(P(v).Ns, () => EmitList(v)); break;
                }
            }

            _w.Line("// <auto-generated/>");
            _w.Line("// Generated by Tessera.Generator. Do not edit.");
            _w.Line("#nullable enable");
            _w.Line("#pragma warning disable CS1591, CS0618, CS0612, CS0108, CS0109");
            _w.Line("using global::System;");
            _w.Line("using global::System.Runtime.CompilerServices;");
            _w.Line("using global::Tessera;");
            foreach (var ns in _byNamespace.Keys.OrderBy(n => n, StringComparer.Ordinal))
            {
                _w.Line();
                if (ns.Length > 0) _w.Open("namespace " + ns);
                foreach (var emit in _byNamespace[ns]) emit();
                if (ns.Length > 0) _w.Close();
            }

            _w.Line();
            _w.Open("namespace " + _ns);
            _w.Line("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
            _w.Open("internal static class TesseraReaders");
            foreach (var s in _types.OfType<StructModel>()) EmitStructReader(s);
            foreach (var a in _accessors) _w.Line(a);
            _w.Close();
            EmitVerifiers();
            _w.Close();
            return _w.ToString();
        }

        private void Add(string ns, Action emit)
        {
            if (!_byNamespace.TryGetValue(ns, out var list)) _byNamespace[ns] = list = new List<Action>();
            list.Add(emit);
        }

        // ------------------------------------------------------------------ names

        private void Place(TypeModel t, string ns, string name, bool isPublic)
        {
            string candidate = name;
            for (int i = 2; ; i++)
            {
                string full = (ns.Length > 0 ? ns + "." : "") + candidate;
                if (!_taken.Contains(full) && _compilation.GetTypeByMetadataName(full) == null)
                {
                    _taken.Add(full);
                    _placed[t] = new Placed { Ns = ns, Name = candidate, Public = isPublic };
                    return;
                }

                candidate = name + i.ToString(CultureInfo.InvariantCulture);
            }
        }

        /// <summary>A read type's place, choosing it on first use (dictionaries and lists are named after their elements).</summary>
        private Placed P(TypeModel t)
        {
            if (_placed.TryGetValue(t, out var placed)) return placed;
            switch (t)
            {
                case ObjectModel o when o.Map != null:
                    Place(t, AnchorNamespace(o.Map.Value) ?? _ns, Short(o.Map.Key) + Short(o.Map.Value) + "Map", ValuePublic(o.Map.Key) && ValuePublic(o.Map.Value));
                    break;
                case VectorModel v:
                    Place(v, AnchorNamespace(v.Element) ?? _ns, Short(v.Element) + "List", ValuePublic(v.Element));
                    break;
                default:
                    throw new InvalidOperationException("No read type for " + t.Key);
            }

            return _placed[t];
        }

        /// <summary>
        /// Read types of this project's classes go next to them; those of other assemblies' classes into the generated
        /// namespace, so that two projects that use them never declare the same type twice.
        /// </summary>
        private string NamespaceOf(INamedTypeSymbol symbol)
        {
            if (!SymbolEqualityComparer.Default.Equals(symbol.ContainingAssembly, _compilation.Assembly)) return _ns;
            var ns = symbol.ContainingNamespace;
            return ns == null || ns.IsGlobalNamespace ? "" : ns.ToDisplayString();
        }

        /// <summary>The namespace a list or dictionary of this element goes to: its element's read type's, if any.</summary>
        private string? AnchorNamespace(ValueModel e)
        {
            switch (e.Kind)
            {
                case WireKind.Object: return e.Object!.Map != null ? AnchorNamespace(e.Object.Map.Value) : P(e.Object).Ns;
                case WireKind.Union: return P(e.Union!).Ns;
                case WireKind.Struct:
                case WireKind.SharedStruct: return NamespaceOf(e.Struct!.Symbol);
                case WireKind.Vector: return AnchorNamespace(e.Vector!.Element);
                default: return null;
            }
        }

        /// <summary>A type's name for read type names: containing types and generic arguments joined with "_".</summary>
        private static string BaseName(INamedTypeSymbol symbol)
        {
            string name = symbol.Name;
            if (symbol.TypeArguments.Length > 0) name += "_" + string.Join("_", symbol.TypeArguments.Select(a => a is INamedTypeSymbol n ? BaseName(n) : a.Name));
            if (symbol.ContainingType != null) name = BaseName(symbol.ContainingType) + "_" + name;
            return Naming.CsIdentifier(name);
        }

        /// <summary>A short name of an element, for list and dictionary type names.</summary>
        private string Short(ValueModel e)
        {
            string nullable = e.IsNullableValueType ? "Nullable" : "";
            switch (e.Kind)
            {
                case WireKind.Object: return P(e.Object!).Name;
                case WireKind.Union: return P(e.Union!).Name;
                case WireKind.Struct: return nullable + BaseName(e.Struct!.Symbol);
                case WireKind.SharedStruct: return nullable + "Shared" + BaseName(e.Struct!.Symbol);
                case WireKind.String: return "String";
                case WireKind.Vector:
                {
                    var inner = e.Vector!.Element;
                    if (GeneratedList(e.Vector)) return P(e.Vector).Name;
                    if (inner.Kind == WireKind.String) return "StringList";
                    return Short(inner) + (IsNullableSpanElement(inner) ? "List" : "Span");
                }
                default:
                    if (e.Enum != null) return nullable + BaseName(e.Enum.Symbol);
                    return nullable + ScalarShort(e.Kind);
            }
        }

        private static string ScalarShort(WireKind k)
        {
            switch (k)
            {
                case WireKind.Bool: return "Boolean";
                case WireKind.Int8: return "SByte";
                case WireKind.UInt8: return "Byte";
                case WireKind.Int16: return "Int16";
                case WireKind.UInt16: return "UInt16";
                case WireKind.Char16: return "Char";
                case WireKind.Int32: return "Int32";
                case WireKind.UInt32: return "UInt32";
                case WireKind.Int64: return "Int64";
                case WireKind.UInt64: return "UInt64";
                case WireKind.Float32: return "Single";
                case WireKind.Float64: return "Double";
                default: return "Value";
            }
        }

        private static bool IsPublic(ISymbol? symbol)
        {
            for (var s = symbol; s != null && s is not INamespaceSymbol; s = s.ContainingSymbol)
            {
                if (s.DeclaredAccessibility != Accessibility.Public) return false;
            }

            if (symbol is INamedTypeSymbol named)
            {
                foreach (var a in named.TypeArguments)
                {
                    if (a is INamedTypeSymbol n && !IsPublic(n)) return false;
                }
            }

            return true;
        }

        /// <summary>Whether everything a value's read type mentions is public.</summary>
        private bool ValuePublic(ValueModel v)
        {
            switch (v.Kind)
            {
                case WireKind.Object: return v.Object!.Map != null ? ValuePublic(v.Object.Map.Key) && ValuePublic(v.Object.Map.Value) : P(v.Object).Public;
                case WireKind.Union: return P(v.Union!).Public;
                case WireKind.Struct:
                case WireKind.SharedStruct: return IsPublic(v.Struct!.Symbol);
                case WireKind.Vector: return ValuePublic(v.Vector!.Element);
                default: return v.Enum == null || IsPublic(v.Enum.Symbol);
            }
        }

        private static string Access(bool isPublic) => isPublic ? "public" : "internal";

        private static string Ident(string name) =>
            SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None || SyntaxFacts.GetContextualKeywordKind(name) == SyntaxKind.UnderscoreToken ? "@" + name : name;

        // ------------------------------------------------------------------ value types

        private static bool IsScalar(WireKind k) => k >= WireKind.Bool && k <= WireKind.Char16;

        /// <summary>Elements read as a span over the buffer: numbers, bools, chars, enums, and plain structs.</summary>
        private static bool IsSpanElement(ValueModel e) =>
            !e.IsNullableValueType && (IsScalar(e.Kind) || (e.Kind == WireKind.Struct && e.Struct!.BlockCopy));

        /// <summary>Nullable elements read by <c>TesseraNullableList&lt;T&gt;</c>.</summary>
        private static bool IsNullableSpanElement(ValueModel e) =>
            e.IsNullableValueType && (IsScalar(e.Kind) || (e.Kind == WireKind.Struct && e.Struct!.BlockCopy));

        /// <summary>Whether a vector's read type is generated (rather than a span or a list type of the runtime).</summary>
        private static bool GeneratedList(VectorModel v)
        {
            var e = v.Element;
            if (IsSpanElement(e) || IsNullableSpanElement(e) || e.Kind == WireKind.String) return false;
            return !(e.Kind == WireKind.Vector && IsSpanElement(e.Vector!.Element));
        }

        /// <summary>The C# type of a number, bool, char or enum.</summary>
        private static string ScalarType(ValueModel v)
        {
            if (v.Enum != null) return v.Enum.CsName;
            switch (v.Kind)
            {
                case WireKind.Bool: return "bool";
                case WireKind.Int8: return "sbyte";
                case WireKind.UInt8: return "byte";
                case WireKind.Int16: return "short";
                case WireKind.UInt16: return "ushort";
                case WireKind.Char16: return "char";
                case WireKind.Int32: return "int";
                case WireKind.UInt32: return "uint";
                case WireKind.Int64: return "long";
                case WireKind.UInt64: return "ulong";
                case WireKind.Float32: return "float";
                case WireKind.Float64: return "double";
                default: throw new InvalidOperationException("not a scalar: " + v.Kind);
            }
        }

        private static string SpanElementType(ValueModel e) => e.Kind == WireKind.Struct ? e.Struct!.CsName : ScalarType(e);

        /// <summary>The C# type a list of <paramref name="v"/>'s element type reads as.</summary>
        private string ListType(VectorModel v)
        {
            var e = v.Element;
            if (IsSpanElement(e)) return $"global::System.ReadOnlySpan<{SpanElementType(e)}>";
            if (IsNullableSpanElement(e)) return $"global::Tessera.TesseraNullableList<{SpanElementType(e)}>";
            if (e.Kind == WireKind.String) return "global::Tessera.TesseraStringList";
            if (e.Kind == WireKind.Vector && IsSpanElement(e.Vector!.Element)) return $"global::Tessera.TesseraSpanList<{SpanElementType(e.Vector.Element)}>";
            return P(v).Full;
        }

        /// <summary>A list read from the vector at <paramref name="at"/> (a <c>ref byte</c> expression; zeros when absent).</summary>
        private string ListFrom(VectorModel v, string at)
        {
            if (IsSpanElement(v.Element)) return $"TesseraReader.Span<{SpanElementType(v.Element)}>({at})";
            return $"new {ListType(v)}({at})";
        }

        /// <summary>The C# type a value of an element, a member or a dictionary value reads as.</summary>
        private string ReadType(ValueModel v)
        {
            switch (v.Kind)
            {
                case WireKind.String: return "string?";
                case WireKind.Object: return P(v.Object!).Full;
                case WireKind.Union: return P(v.Union!).Full;
                case WireKind.Vector: return ListType(v.Vector!);
                case WireKind.Struct:
                case WireKind.SharedStruct: return v.Struct!.CsName + (v.IsNullableValueType ? "?" : "");
                default: return ScalarType(v) + (v.IsNullableValueType ? "?" : "");
            }
        }

        /// <summary>The value a read type has when absent (a ref struct's default would hold a null reference).</summary>
        private string AbsentValue(ValueModel v)
        {
            switch (v.Kind)
            {
                case WireKind.String: return "null";
                case WireKind.Object:
                case WireKind.Union: return $"new {ReadType(v)}(ref Absent)";
                case WireKind.Vector: return ListFrom(v.Vector!, "ref Absent");
                default: return "default";
            }
        }

        // ------------------------------------------------------------------ objects

        private void EmitObject(ObjectModel o)
        {
            var me = P(o);
            string name = me.Name;
            _w.Line();
            _w.Line($"/// <summary>");
            _w.Line($"/// A {Xml(o.DisplayName)} stored in a Tessera buffer: its fields, read where they are stored, without copying it.");
            _w.Line($"/// Get the one a buffer holds with <see cref=\"Read\"/>.");
            _w.Line($"/// </summary>");
            _w.Open($"{Access(me.Public)} readonly ref struct {name}");
            _w.Line("private readonly ref byte _p;");
            _w.Line();
            _w.Line($"/// <summary>The {Xml(o.DisplayName)} at <paramref name=\"p\"/> (for generated code).</summary>");
            _w.Line("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
            _w.Line($"public {name}(ref byte p) => _p = ref p;");
            _w.Line();
            _w.Line("/// <summary>");
            _w.Line($"/// Checks <paramref name=\"buffer\"/> and returns the {Xml(o.DisplayName)} it holds. The result reads");
            _w.Line("/// <paramref name=\"buffer\"/>, so keep it unchanged while you use the result.");
            _w.Line("/// </summary>");
            _w.Line("/// <exception cref=\"TesseraReadException\">The buffer cannot be read; its <c>Error</c> says why.</exception>");
            _w.Open($"public static {name} Read(global::System.ReadOnlySpan<byte> buffer, TesseraReadOptions? options = null)");
            _w.Line($"ref readonly byte root = ref TesseraReader.Open(buffer, global::{_ns}.TesseraSchema.T{o.Index}, global::{_ns}.TesseraVerifiers.O{o.Index}, options, out TesseraReadError error);");
            _w.Line("if (error != TesseraReadError.None) throw new TesseraReadException(error);");
            _w.Line($"return new {name}(ref Unsafe.AsRef(in root));");
            _w.Close();
            _w.Line();
            _w.Line($"/// <summary>Like <see cref=\"Read\"/>, but returns false and the reason instead of throwing.</summary>");
            _w.Open($"public static bool TryRead(global::System.ReadOnlySpan<byte> buffer, out {name} value, out TesseraReadError error, TesseraReadOptions? options = null)");
            _w.Line($"ref readonly byte root = ref TesseraReader.Open(buffer, global::{_ns}.TesseraSchema.T{o.Index}, global::{_ns}.TesseraVerifiers.O{o.Index}, options, out error);");
            _w.Line($"value = new {name}(ref Unsafe.AsRef(in root));");
            _w.Line("return error == TesseraReadError.None;");
            _w.Close();
            _w.Line();
            _w.Line("/// <summary>Whether the object is absent: it was null when written.</summary>");
            _w.Line("public bool IsNull => TesseraReader.IsAbsent(in _p);");
            _w.Line();
            _w.Line("private static ref byte Absent => ref Unsafe.AsRef(in TesseraReader.Zeros);");
            _w.Line();
            _w.Line("private uint H(int word) => Unsafe.ReadUnaligned<uint>(ref Unsafe.Add(ref _p, 4 * word));");

            var used = new HashSet<string>(o.Members.Select(m => Ident(m.CsName)), StringComparer.Ordinal) { "IsNull", "Read", "TryRead", "H", "Absent", "_p" };
            string Unique(string n)
            {
                while (!used.Add(n)) n += "_";
                return n;
            }

            foreach (var m in o.Members)
            {
                string member = Ident(m.CsName);
                string access = Access(me.Public && ValuePublic(m.Value));
                string present = m.IsFixed ? "!IsNull" : $"(H({m.Bit / 32}) & 0x{1u << (m.Bit % 32):X}u) != 0";
                _w.Line();
                _w.Line($"/// <summary>{Xml(m.CsTypeDisplay)} {Xml(m.CsName)}{DefaultNote(m)}.</summary>");
                if (m.Value.Kind == WireKind.Bool) EmitBool(m, member, access);
                else if (m.IsFixed) EmitFixed(o, m, member, access);
                else EmitCell(o, m, member, access, present, Unique);

                _w.Line();
                _w.Line(m.IsFixed
                    ? $"/// <summary>Whether {Xml(m.CsName)} was stored: always, unless the whole object is absent.</summary>"
                    : $"/// <summary>Whether {Xml(m.CsName)} was stored (false when it was null{(m.Value.IsNullableValueType || WireFormat.IsReference(m.Value.Kind) ? "" : " or equal to its default")}).</summary>");
                _w.Line($"public bool {Unique("Has" + m.CsName)} => {present};");
            }

            _w.Close();
        }

        private static string DefaultNote(MemberModel m)
        {
            if (m.Value.IsNullableValueType || WireFormat.IsReference(m.Value.Kind) || m.Value.Kind == WireKind.Struct) return "";
            if (!m.HasCustomDefault || m.DefaultValue == null) return "";
            string shown = m.DefaultValue is bool b ? (b ? "true" : "false") : Convert.ToString(m.DefaultValue, CultureInfo.InvariantCulture) ?? "";
            if (m.Value.Enum != null)
            {
                long raw = Convert.ToInt64(m.DefaultValue, CultureInfo.InvariantCulture);
                foreach (var kv in m.Value.Enum.Values)
                {
                    if (Convert.ToInt64(kv.Value, CultureInfo.InvariantCulture) != raw) continue;
                    shown = m.Value.Enum.Symbol.Name + "." + kv.Key;
                    break;
                }
            }

            return $" (when it was not stored: {Xml(shown)})";
        }

        private void EmitBool(MemberModel m, string member, string access)
        {
            int word = m.Bit / 32, bit = m.Bit % 32;
            if (m.Value.IsNullableValueType)
            {
                _w.Open($"{access} bool? {member}");
                _w.Line("get");
                _w.Line("{");
                _w.Indent();
                _w.Line($"uint w = H({word}) >> {bit};");
                _w.Line("return (w & 1u) == 0 ? null : ((w >> 1) & 1u) != 0;");
                _w.Outdent();
                _w.Line("}");
                _w.Close();
            }
            else if (m.DefaultValue is bool d && d)
            {
                // Default true: absent, or present with its value bit set.
                _w.Open($"{access} bool {member}");
                _w.Line("get");
                _w.Line("{");
                _w.Indent();
                _w.Line($"uint w = H({word}) >> {bit};");
                _w.Line("return ((~w | (w >> 1)) & 1u) != 0;");
                _w.Outdent();
                _w.Line("}");
                _w.Close();
            }
            else
            {
                // The value bit is set only together with the present bit.
                _w.Line($"{access} bool {member} => ((H({word}) >> {bit + 1}) & 1u) != 0;");
            }
        }

        private void EmitFixed(ObjectModel o, MemberModel m, string member, string access)
        {
            string at = $"ref Unsafe.Add(ref _p, {4 * o.HeaderWords + m.FixedOffset})";
            var v = m.Value;
            if (v.Kind == WireKind.Struct)
            {
                // An absent object reads its fixed cells from zeros: a struct's default.
                _w.Line($"{access} {v.Struct!.CsName} {member} => {StructRead(v.Struct, at)};");
                return;
            }

            string type = ScalarType(v);
            string read = $"Unsafe.ReadUnaligned<{type}>({at})";
            string? def = Default(m);
            bool zeroDefault = def == null || IsZero(m.DefaultValue);
            _w.Line(zeroDefault ? $"{access} {type} {member} => {read};" : $"{access} {type} {member} => IsNull ? {def} : {read};");
        }

        /// <summary>A member's declared default as a C# constant, or null when it is the type's default.</summary>
        private static string? Default(MemberModel m) => m.DefaultValue == null ? null : TesseraGenerator.CsConstant(m);

        private static bool IsZero(object? d)
        {
            switch (d)
            {
                case null: return true;
                case bool b: return !b;
                case float f: return BitConverter.ToInt32(BitConverter.GetBytes(f), 0) == 0;
                case double x: return BitConverter.DoubleToInt64Bits(x) == 0;
                case char c: return c == '\0';
                default: return Convert.ToDecimal(d, CultureInfo.InvariantCulture) == 0;
            }
        }

        private void EmitCell(ObjectModel o, MemberModel m, string member, string access, string present, Func<string, string> unique)
        {
            var v = m.Value;
            string cell = $"ref Unsafe.Add(ref _p, {CellOffset(o, m)})";
            string type = ReadType(v);
            void Getter(string absent, string read)
            {
                _w.Open($"{access} {type} {member}");
                _w.Line("get");
                _w.Line("{");
                _w.Indent();
                _w.Line($"if (!({present})) return {absent};");
                _w.Line($"return {read};");
                _w.Outdent();
                _w.Line("}");
                _w.Close();
            }

            switch (v.Kind)
            {
                case WireKind.String:
                    Getter("null", $"TesseraReader.String(ref TesseraReader.Target({cell}))");
                    _w.Line();
                    _w.Line($"/// <summary>The UTF-8 bytes of {Xml(m.CsName)}, without decoding them (empty when it is null).</summary>");
                    _w.Open($"{access} global::System.ReadOnlySpan<byte> {unique(m.CsName + "Utf8")}");
                    _w.Line("get");
                    _w.Line("{");
                    _w.Indent();
                    _w.Line($"if (!({present})) return default;");
                    _w.Line($"return TesseraReader.Utf8(ref TesseraReader.Target({cell}));");
                    _w.Outdent();
                    _w.Line("}");
                    _w.Close();
                    break;
                case WireKind.Object:
                case WireKind.Vector:
                    Getter(AbsentValue(v), v.Kind == WireKind.Object
                        ? $"new {type}(ref TesseraReader.Target({cell}))"
                        : ListFrom(v.Vector!, $"ref TesseraReader.Target({cell})"));
                    break;
                case WireKind.Union:
                    Getter(AbsentValue(v), $"new {type}({cell})");
                    break;
                case WireKind.Struct:
                    Getter(v.IsNullableValueType ? "null" : "default", StructRead(v.Struct!, cell));
                    break;
                case WireKind.SharedStruct:
                    Getter(v.IsNullableValueType ? "null" : "default", StructRead(v.Struct!, $"ref TesseraReader.Target({cell})"));
                    break;
                default:
                {
                    string absent = v.IsNullableValueType ? "null" : Default(m) ?? "default";
                    Getter(absent, $"Unsafe.ReadUnaligned<{ScalarType(v)}>({cell})");
                    break;
                }
            }
        }

        /// <summary>
        /// Byte offset of a cell from its object's start: the header and fixed cells, then the sizes of the present cells
        /// before it, one population count per cell size and header word.
        /// </summary>
        private static string CellOffset(ObjectModel o, MemberModel m)
        {
            var terms = new List<string> { (4 * o.HeaderWords + o.FixedSize).ToString(CultureInfo.InvariantCulture) };
            foreach (var g in o.Cells.Where(c => c.Bit < m.Bit).GroupBy(c => c.CellSize).OrderBy(g => g.Key))
            {
                var masks = new uint[o.HeaderWords];
                foreach (var c in g) masks[c.Bit / 32] |= 1u << (c.Bit % 32);
                for (int w = 0; w < masks.Length; w++)
                {
                    if (masks[w] == 0) continue;
                    string count = $"global::System.Numerics.BitOperations.PopCount(H({w}) & 0x{masks[w]:X}u)";
                    terms.Add(g.Key == 1 ? count : $"{g.Key} * {count}");
                }
            }

            return terms.Count == 1 ? terms[0] : "(nint)(" + string.Join(" + ", terms) + ")";
        }

        // ------------------------------------------------------------------ structs

        private string StructRead(StructModel s, string at)
        {
            _structReaders.Add(s);
            return $"global::{_ns}.TesseraReaders.Struct{s.Index}({at})";
        }

        /// <summary>
        /// Builds a struct from its bytes. A plain struct (the same bytes in memory) is one copy; any other has each field
        /// set, bools normalized to 0 or 1, through an UnsafeAccessor where the field cannot be named.
        /// </summary>
        private void EmitStructReader(StructModel s)
        {
            _w.Line();
            _w.Open($"public static {s.CsName} Struct{s.Index}(ref byte p)");
            if (s.BlockCopy) _w.Line($"if (Unsafe.SizeOf<{s.CsName}>() == {s.Size}) return Unsafe.ReadUnaligned<{s.CsName}>(ref p);");
            _w.Line($"{s.CsName} v = default;");
            foreach (var f in s.Fields)
            {
                string at = f.Offset == 0 ? "ref p" : $"ref Unsafe.Add(ref p, {f.Offset})";
                string value;
                if (f.Struct != null) value = StructRead(f.Struct, at);
                else if (f.Kind == WireKind.Bool) value = $"Unsafe.Add(ref p, {f.Offset}) != 0";
                else value = $"Unsafe.ReadUnaligned<{f.CsType}>({at})";
                _w.Line($"{FieldTarget(s, f)} = {value};");
            }

            _w.Line("return v;");
            _w.Close();
        }

        private string FieldTarget(StructModel s, StructField f)
        {
            if (f.FieldAccessible) return $"Unsafe.AsRef(in v.{Ident(f.FieldName)})";
            string accessor = "__TesseraSet_" + Naming.CsIdentifier(s.WireName) + "_" + Naming.CsIdentifier(f.FieldName);
            string declaration = $"[UnsafeAccessor(UnsafeAccessorKind.Field, Name = {Naming.CsString(f.FieldName)})] private static extern ref {f.CsType} {accessor}(ref {s.CsName} owner);";
            if (!_accessors.Contains(declaration)) _accessors.Add(declaration);
            return $"{accessor}(ref v)";
        }

        // ------------------------------------------------------------------ unions

        private void EmitUnion(UnionModel u)
        {
            var me = P(u);
            string name = me.Name;
            var members = u.Members.OrderBy(x => x.Tag).ToList();
            var names = new Dictionary<UnionMember, string>();
            var used = new HashSet<string>(StringComparer.Ordinal) { "None", "Tag", "Tags", "IsNull", "Absent" };
            foreach (var m in members)
            {
                string n = BaseName(m.Type.Symbol);
                while (!used.Add(n) || !used.Add("Is" + n) || !used.Add("As" + n)) n += "_";
                names[m] = n;
            }

            _w.Line();
            _w.Line($"/// <summary>A {Xml(u.DisplayName)} stored in a Tessera buffer: one of {Xml(string.Join(", ", members.Select(m => m.Type.DisplayName)))}, or null.</summary>");
            _w.Open($"{Access(me.Public)} readonly ref struct {name}");
            _w.Line("private readonly ref byte _cell;   // the type's tag, then the offset to the object (from its own position); zeros when absent");
            _w.Line();
            _w.Line($"/// <summary>The value whose 8 bytes are at <paramref name=\"cell\"/> (for generated code).</summary>");
            _w.Line("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
            _w.Line($"public {name}(ref byte cell) => _cell = ref cell;");
            _w.Line();
            _w.Line("/// <summary>The types the value can have.</summary>");
            _w.Open("public enum Tags : uint");
            _w.Line("/// <summary>Null.</summary>");
            _w.Line("None = 0,");
            foreach (var m in members)
            {
                _w.Line($"/// <summary>{Xml(m.Type.DisplayName)}.</summary>");
                _w.Line($"{names[m]} = 0x{m.Tag:X8}u,");
            }

            _w.Close();
            _w.Line();
            _w.Line("/// <summary>The value's type (<see cref=\"Tags.None\"/> when it is null).</summary>");
            _w.Line("public Tags Tag => (Tags)Unsafe.ReadUnaligned<uint>(ref _cell);");
            _w.Line();
            _w.Line("/// <summary>Whether the value is null.</summary>");
            _w.Line("public bool IsNull => Unsafe.ReadUnaligned<uint>(ref Unsafe.Add(ref _cell, 4)) == 0;");
            _w.Line();
            _w.Line("private static ref byte Absent => ref Unsafe.AsRef(in TesseraReader.Zeros);");
            _w.Line();
            _w.Line("private bool Is(uint tag) => Unsafe.ReadUnaligned<uint>(ref _cell) == tag && Unsafe.ReadUnaligned<uint>(ref Unsafe.Add(ref _cell, 4)) != 0;");
            foreach (var m in members)
            {
                string view = P(m.Type).Full;
                string access = Access(me.Public && P(m.Type).Public);
                _w.Line();
                _w.Line($"/// <summary>Whether the value is a {Xml(m.Type.DisplayName)}.</summary>");
                _w.Line($"{access} bool Is{names[m]} => Is(0x{m.Tag:X8}u);");
                _w.Line();
                _w.Line($"/// <summary>The value as a {Xml(m.Type.DisplayName)}; absent (<c>IsNull</c>) when it is another type or null.</summary>");
                _w.Line($"{access} {view} As{names[m]} => Is(0x{m.Tag:X8}u) ? new {view}(ref TesseraReader.Target(ref Unsafe.Add(ref _cell, 4))) : new {view}(ref Absent);");
            }

            _w.Close();
        }

        // ------------------------------------------------------------------ lists

        /// <summary>Item <paramref name="index"/> of the vector at <paramref name="v"/> (a <c>ref byte</c> variable).</summary>
        private string ElementAt(ValueModel e, string v, string index)
        {
            string slot = $"ref Unsafe.Add(ref {v}, 4 + 4 * {index})";
            switch (e.Kind)
            {
                case WireKind.String:
                    return $"Unsafe.ReadUnaligned<uint>({slot}) == 0 ? null : TesseraReader.String(ref TesseraReader.Target({slot}))";
                case WireKind.Object:
                    return $"new {ReadType(e)}(ref TesseraReader.TargetOrAbsent({slot}))";
                case WireKind.Union:
                    return $"new {ReadType(e)}(ref Unsafe.Add(ref {v}, 4 + 8 * {index}))";
                case WireKind.Vector:
                    return ListFrom(e.Vector!, $"ref TesseraReader.TargetOrAbsent({slot})");
                case WireKind.SharedStruct:
                    return $"Unsafe.ReadUnaligned<uint>({slot}) == 0 ? {(e.IsNullableValueType ? "null" : "default")} : {StructRead(e.Struct!, $"ref TesseraReader.Target({slot})")}";
                case WireKind.Struct when e.IsNullableValueType:
                    return $"NullableAt(ref {v}, {index}) ? {StructRead(e.Struct!, $"ref Unsafe.Add(ref {v}, ValuesAt(ref {v}) + {e.Struct!.Size} * {index})")} : null";
                case WireKind.Struct:
                    return StructRead(e.Struct!, $"ref Unsafe.Add(ref {v}, 4 + {e.Struct!.Size} * {index})");
                default:
                {
                    string type = ScalarType(e);
                    int size = e.Kind == WireKind.Bool ? 1 : WireFormat.CellSize(e.Kind);
                    if (e.IsNullableValueType) return $"NullableAt(ref {v}, {index}) ? Unsafe.ReadUnaligned<{type}>(ref Unsafe.Add(ref {v}, ValuesAt(ref {v}) + {size} * {index})) : null";
                    return $"Unsafe.ReadUnaligned<{type}>(ref Unsafe.Add(ref {v}, 4 + {size} * {index}))";
                }
            }
        }

