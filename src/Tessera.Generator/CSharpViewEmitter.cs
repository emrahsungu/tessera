            _w.Line();
            _w.Line("/// <summary>Moves to the next item.</summary>");
            _w.Line("public bool MoveNext() => ++_index < _list.Count;");
            _w.Close();
            _w.Close();
        }

        /// <summary>Helpers for lists of nullable values: a presence bit per item, then every item's value.</summary>
        private void EmitNullableHelpers()
        {
            _w.Line();
            _w.Line("private static bool NullableAt(ref byte v, int index) => ((Unsafe.ReadUnaligned<uint>(ref Unsafe.Add(ref v, 4 + 4 * (index >> 5))) >> (index & 31)) & 1u) != 0;");
            _w.Line();
            _w.Line("private static int ValuesAt(ref byte v) => 4 + 4 * (((int)Unsafe.ReadUnaligned<uint>(ref v) + 31) >> 5);");
        }

        private string Describe(ValueModel e)
        {
            switch (e.Kind)
            {
                case WireKind.Object: return e.Object!.DisplayName;
                case WireKind.Union: return e.Union!.DisplayName;
                case WireKind.Struct:
                case WireKind.SharedStruct: return e.Struct!.DisplayName + (e.IsNullableValueType ? "?" : "");
                case WireKind.Vector: return "lists of " + Describe(e.Vector!.Element);
                case WireKind.String: return "string";
                default: return ScalarType(e) + (e.IsNullableValueType ? "?" : "");
            }
        }

