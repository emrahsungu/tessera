    {
        /// <summary>Element type as written in a generic argument (keeps Nullable&lt;T&gt;).</summary>
        public static string CsTypeWithNullable(this ValueModel v) => v.IsNullableValueType ? v.CsType + "?" : v.CsType;
    }
