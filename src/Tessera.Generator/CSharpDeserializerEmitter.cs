using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Tessera.Generator
{
    /// <summary>
    /// Emits the deserializers (<c>TesseraSerializer.Deserialize&lt;T&gt;</c>): for each class a method that creates it
    /// from a buffer, setting every member the writer stored. A member is set through a constructor parameter of its name
    /// (when the class has no constructor without parameters), an object initializer, or, where code outside the class
    /// cannot set it (a private or init-only setter, a get-only auto-property, a read-only field), an UnsafeAccessor.
    /// Lists and dictionaries are created as their declared types.
    /// </summary>
    /// <remarks>
    /// Each method takes a type argument that says whether to check what it reads, compiled into two versions: one that
    /// checks the buffer as it reads it, with the rules of the generated checks (<c>TesseraVerifiers</c>), and one that
    /// reads a buffer checked before, or trusted. A failed check gives up (<c>TesseraDeserializer.Fail</c>): the buffer is
    /// then checked on its own.
    /// </remarks>
    internal sealed class CSharpDeserializerEmitter
    {
        private readonly List<TypeModel> _types;
        private readonly string _ns;
        private readonly Compilation _compilation;
        private readonly CodeWriter _w = new CodeWriter();
        private readonly List<string> _accessors = new List<string>();
        private readonly Dictionary<string, Made> _collections = new Dictionary<string, Made>(StringComparer.Ordinal);
        private readonly List<Made> _pending = new List<Made>();

        /// <summary>A list or dictionary of one stored type created as one C# type.</summary>
        private sealed class Made
        {
            public string Name = "";
            public int Id;                     // its key among the items created once (TesseraDeserializer.Shared)
            public TypeModel Wire = null!;     // a VectorModel, or an ObjectModel with Map
            public ITypeSymbol Type = null!;   // the declared type
        }

        private enum Setter { Initializer, Assign, Field, Method }

        private enum Shape { Array, List, Add, Wrap, None }

        public CSharpDeserializerEmitter(List<TypeModel> types, string generatedNamespace, Compilation compilation)
        {
            _types = types;
            _ns = generatedNamespace;
            _compilation = compilation;
        }

        public string Emit()
        {
            var objects = _types.OfType<ObjectModel>().Where(o => o.Map == null && !o.Symbol.IsAbstract).ToList();
            _w.Line("// <auto-generated/>");
            _w.Line("// Generated by Tessera.Generator. Do not edit.");
            _w.Line("#nullable disable");
            _w.Line("#pragma warning disable CS1591, CS0618, CS0612");
            _w.Line("using global::System.Runtime.CompilerServices;");
            _w.Line("using global::Tessera;");
            _w.Line();
            _w.Open("namespace " + _ns);
            _w.Line("/// <summary>Creates objects from buffers (for TesseraSerializer.Deserialize).</summary>");
            _w.Line("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
            _w.Open("internal static class TesseraDeserializers");
            foreach (var o in objects) EmitObject(o);
            foreach (var u in _types.OfType<UnionModel>()) EmitUnion(u);
            for (int i = 0; i < _pending.Count; i++) EmitCollection(_pending[i]);   // emitting one can add more
            if (_accessors.Count > 0) _w.Line();
            foreach (var a in _accessors) _w.Line(a);
            _w.Close();
            _w.Line();
            _w.Line("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
            _w.Open("internal static class TesseraReadRegistration");
            _w.Line("[ModuleInitializer]");
            _w.Open("internal static void Register()");
            foreach (var o in objects)
            {
                _w.Line($"TesseraModel<{o.CsName}>.RegisterRead(TesseraSchema.T{o.Index}, TesseraVerifiers.O{o.Index}, " +
                        $"TesseraDeserializers.O{o.Index}<TesseraChecked>, TesseraDeserializers.O{o.Index}<TesseraUnchecked>, TesseraDeserializers.O{o.Index}<TesseraShared>);");
            }

            _w.Close();
            _w.Close();
            _w.Close();
            return _w.ToString();
        }

        // ------------------------------------------------------------------ objects

        private void EmitObject(ObjectModel o)
        {
            string type = o.CsName;
            var symbol = o.Symbol;
            _w.Line();
            _w.Open($"public static {type} O{o.Index}<TC>(ref TesseraDeserializer d, ref byte p, int depth) where TC : struct, ITesseraReadMode");
            if (!o.IsValueType) _w.Line($"if (TC.Share && d.Find(ref p, {o.Index}) is {type} found) return found;");
            // An object's first 4 bytes are in the buffer when its offset passed the check (TesseraDeserializer.TryChecked).
            int start = 4 * o.HeaderWords + o.FixedSize;
            if (start == 4) Checked("d.Enter(depth);");
            else Checked("d.Enter(depth);", $"d.Range(ref p, {start});");
            for (int w = 0; w < o.HeaderWords; w++) _w.Line($"uint h{w} = Unsafe.ReadUnaligned<uint>({(w == 0 ? "ref p" : $"ref Unsafe.Add(ref p, {4 * w})")});");
            CheckHeader(o, start);

            // How to create it: a constructor without parameters, else one whose parameters are members, else without
            // running a constructor.
            var bound = new Dictionary<MemberModel, IParameterSymbol>();
            IMethodSymbol? parameterless = symbol.InstanceConstructors.FirstOrDefault(c => c.Parameters.Length == 0);
            IMethodSymbol? ctor = parameterless != null && Accessible(parameterless) ? parameterless : BestConstructor(o, bound);
            bool initializer = ctor != null;
            string create;
            if (ctor != null)
            {
                string args = string.Join(", ", ctor.Parameters.Select(param => Value(o, bound.First(kv => SymbolEqualityComparer.Default.Equals(kv.Value, param)).Key)));
                create = ctor.Parameters.Length == 0 ? $"new {type}" : $"new {type}({args})";
            }
            else if (parameterless != null)
            {
                string accessor = $"__TesseraNew{o.Index}";
                _accessors.Add($"[UnsafeAccessor(UnsafeAccessorKind.Constructor)] private static extern {type} {accessor}();");
                create = accessor + "()";
            }
            else
            {
                create = o.IsValueType ? "default" : $"({type})RuntimeHelpers.GetUninitializedObject(typeof({type}))";
            }

            var inits = new List<string>();
            var statements = new List<string>();
            string owner = o.IsValueType ? "ref v" : "v";
            foreach (var m in o.Members)
            {
                if (bound.ContainsKey(m)) continue;
                string value = Value(o, m);
                string name = Ident(m.CsName);
                switch (How(m, initializer, out string target))
                {
                    case Setter.Initializer:
                        inits.Add($"{name} = {value}");
                        break;
                    case Setter.Assign:
                        statements.Add($"v.{name} = {value};");
                        break;
                    case Setter.Field:
                    {
                        string accessor = $"__TesseraField{o.Index}_{Naming.CsIdentifier(m.CsName)}";
                        _accessors.Add($"[UnsafeAccessor(UnsafeAccessorKind.Field, Name = {Naming.CsString(target)})] private static extern ref {Cs(MemberType(m))} " +
                                       $"{accessor}({OwnerParameter(o, m)});");
                        statements.Add($"{accessor}({owner}) = {value};");
                        break;
                    }
                    default:
                    {
                        string accessor = $"__TesseraSet{o.Index}_{Naming.CsIdentifier(m.CsName)}";
                        _accessors.Add($"[UnsafeAccessor(UnsafeAccessorKind.Method, Name = {Naming.CsString(target)})] private static extern void " +
                                       $"{accessor}({OwnerParameter(o, m)}, {Cs(MemberType(m))} value);");
                        statements.Add($"{accessor}({owner}, {value});");
                        break;
                    }
                }
            }

            // An object creation must set the required members it does not store (TesseraIgnore) too.
            if (ctor != null && !ctor.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == "System.Diagnostics.CodeAnalysis.SetsRequiredMembersAttribute"))
            {
                var stored = new HashSet<string>(o.Members.Select(m => m.CsName), StringComparer.Ordinal);
                for (var t = symbol; t != null; t = t.BaseType)
                {
                    foreach (var member in t.GetMembers())
                    {
                        bool required = member is IFieldSymbol { IsRequired: true } || member is IPropertySymbol { IsRequired: true };
                        if (required && stored.Add(member.Name)) inits.Add($"{Ident(member.Name)} = default");
                    }
                }
            }

            if (!initializer)
            {
                _w.Line($"{type} v = {create};");
            }
            else if (inits.Count == 0)
            {
                _w.Line($"var v = {create}{(ctor!.Parameters.Length == 0 ? "()" : "")};");
            }
            else
            {
                _w.Line($"var v = {create}");
                _w.Line("{");
                _w.Indent();
                foreach (var i in inits) _w.Line(i + ",");
                _w.Outdent();
                _w.Line("};");
            }

            foreach (var s in statements) _w.Line(s);
            _w.Line(o.IsValueType ? "return v;" : $"return d.Keep<TC, {type}>(ref p, {o.Index}, v);");
            _w.Close();
        }

        /// <summary>
        /// The accessible constructor with the most parameters, all of them members by name (any case) and type, as a
        /// record's primary constructor; <paramref name="bound"/> gets the member of each parameter.
        /// </summary>
        private IMethodSymbol? BestConstructor(ObjectModel o, Dictionary<MemberModel, IParameterSymbol> bound)
        {
            if (o.Symbol.IsAbstract) return null;
            foreach (var c in o.Symbol.InstanceConstructors.Where(c => c.Parameters.Length > 0 && Accessible(c)).OrderByDescending(c => c.Parameters.Length))
            {
                var map = new Dictionary<MemberModel, IParameterSymbol>();
                foreach (var param in c.Parameters)
                {
                    if (param.RefKind == RefKind.Ref || param.RefKind == RefKind.Out) break;
                    var m = o.Members.FirstOrDefault(x => !map.ContainsKey(x) && string.Equals(x.CsName, param.Name, StringComparison.OrdinalIgnoreCase) &&
                                                          SymbolEqualityComparer.Default.Equals(MemberType(x), param.Type));
                    if (m == null) break;
                    map[m] = param;
                }

                if (map.Count != c.Parameters.Length) continue;
                foreach (var kv in map) bound[kv.Key] = kv.Value;
                return c;
            }

            return null;
        }

        /// <summary>How a member is set; <paramref name="target"/> names the field or setter an UnsafeAccessor reaches.</summary>
        private Setter How(MemberModel m, bool initializer, out string target)
        {
            target = "";
            switch (m.Symbol)
            {
                case IFieldSymbol f:
                    if (!f.IsReadOnly) return initializer ? Setter.Initializer : Setter.Assign;
                    target = f.Name;
                    return Setter.Field;
                case IPropertySymbol p:
                {
                    var set = p.SetMethod;
                    if (set != null && Accessible(set))
                    {
                        if (initializer) return Setter.Initializer;
                        if (!set.IsInitOnly) return Setter.Assign;
                    }

                    // Auto-properties through their field (an init-only setter cannot be named by an UnsafeAccessor everywhere).
                    var backing = p.ContainingType.GetMembers().OfType<IFieldSymbol>().FirstOrDefault(f => SymbolEqualityComparer.Default.Equals(f.AssociatedSymbol, p));
                    if (backing != null)
                    {
                        target = backing.Name;
                        return Setter.Field;
                    }

                    target = set!.Name;
                    return Setter.Method;
                }
                default:
                    throw new InvalidOperationException("not a field or property: " + m.Symbol);
            }
        }

        /// <summary>The first parameter of an UnsafeAccessor of member <paramref name="m"/>: the type that declares it.</summary>
        private static string OwnerParameter(ObjectModel o, MemberModel m) =>
            o.IsValueType ? $"ref {Cs(m.Symbol.ContainingType)} owner" : $"{Cs(m.Symbol.ContainingType)} owner";

        /// <summary>A member's value, read from the object at <c>p</c> whose header words are <c>h0</c>, <c>h1</c>...</summary>
        private string Value(ObjectModel o, MemberModel m)
        {
            var v = m.Value;
            if (v.Kind == WireKind.Bool)
            {
                int word = m.Bit / 32, bit = m.Bit % 32;
                if (v.IsNullableValueType) return $"((h{word} >> {bit}) & 1u) == 0 ? (bool?)null : ((h{word} >> {bit + 1}) & 1u) != 0";
                // Default true: absent, or present with its value bit set. The value bit is set only with the present bit.
                if (m.DefaultValue is bool b && b) return $"((~(h{word} >> {bit}) | (h{word} >> {bit + 1})) & 1u) != 0";
                return $"((h{word} >> {bit + 1}) & 1u) != 0";
            }

            if (m.IsFixed)
            {
                string at = $"ref Unsafe.Add(ref p, {4 * o.HeaderWords + m.FixedOffset})";
                return v.Kind == WireKind.Struct ? StructRead(v.Struct!, at) : $"Unsafe.ReadUnaligned<{Scalar(v)}>({at})";
            }

            string present = $"(h{m.Bit / 32} & 0x{1u << (m.Bit % 32):X}u) != 0";
            string read = Read(v, MemberType(m), $"ref Unsafe.Add(ref p, {CellOffset(o, m)})");
            string absent = !v.IsNullableValueType && IsScalar(v.Kind) && m.DefaultValue != null ? TesseraGenerator.CsConstant(m) ?? "default" : "default";
            return $"{present} ? {read} : {absent}";
        }

        /// <summary>
        /// The value of a cell at <paramref name="cell"/> (a <c>ref byte</c> expression) that is present, of the type
        /// <paramref name="declared"/> (lists and dictionaries are created as that type).
        /// </summary>
        private string Read(ValueModel v, ITypeSymbol declared, string cell)
        {
            string nullable = v.IsNullableValueType ? $"({(v.Kind == WireKind.Struct || v.Kind == WireKind.SharedStruct ? v.Struct!.CsName : v.Kind == WireKind.Object ? v.Object!.CsName : Scalar(v))}?)" : "";
            string target = $"ref d.Target<TC>({cell})";
            switch (v.Kind)
            {
                case WireKind.String: return $"d.String<TC>({target})";
                case WireKind.Object when v.Object!.Map != null: return $"{Collection(v.Object, declared)}<TC>(ref d, {target}, depth + 1)";
                case WireKind.Object: return $"{nullable}O{v.Object.Index}<TC>(ref d, {target}, depth + 1)";
                case WireKind.Vector: return $"{Collection(v.Vector!, declared)}<TC>(ref d, {target}, depth + 1)";
                case WireKind.Union: return $"U{v.Union!.Index}<TC>(ref d, {cell}, depth + 1)";
                case WireKind.Struct: return nullable + StructRead(v.Struct!, cell);
                case WireKind.SharedStruct: return nullable + StructRead(v.Struct!, $"ref d.SharedStruct<TC>({cell}, {v.Struct!.Size})");
                default: return $"{nullable}Unsafe.ReadUnaligned<{Scalar(v)}>({cell})";
            }
        }

        /// <summary>A cell's position in its object: the header and fixed cells, then the present cells before it.</summary>
        private static string CellOffset(ObjectModel o, MemberModel m) => CellsBefore(o, m.Bit);

        /// <summary>The bytes from an object's start to cell <paramref name="bit"/> (past the last cell for a larger bit).</summary>
        private static string CellsBefore(ObjectModel o, int bit)
        {
            var terms = new List<string> { (4 * o.HeaderWords + o.FixedSize).ToString(CultureInfo.InvariantCulture) };
            foreach (var g in o.Cells.Where(c => c.Bit < bit).GroupBy(c => c.CellSize).OrderBy(g => g.Key))
            {
                var masks = new uint[o.HeaderWords];
                foreach (var c in g) masks[c.Bit / 32] |= 1u << (c.Bit % 32);
                for (int w = 0; w < masks.Length; w++)
                {
                    if (masks[w] == 0) continue;
                    string count = $"global::System.Numerics.BitOperations.PopCount(h{w} & 0x{masks[w]:X}u)";
                    terms.Add(g.Key == 1 ? count : $"{g.Key} * {count}");
                }
            }

            return string.Join(" + ", terms);
        }

        private string StructRead(StructModel s, string at) => $"global::{_ns}.TesseraReaders.Struct{s.Index}({at})";

        // ------------------------------------------------------------------ checks

        /// <summary>
        /// Statements that run only in the checking version; the unchecked one counts the item instead (to share the items
        /// of a buffer that holds far fewer than the references to them).
        /// </summary>
        private void Checked(params string[] statements)
        {
            _w.Open("if (TC.Check)");
            foreach (var line in statements) _w.Line(line);
            _w.Close();
            _w.Open("else if (!TC.Share)");
            _w.Line("d.Count();");
            _w.Close();
            _w.Line();
        }

        /// <summary>
        /// An object's header (no bit set that the type does not use, no bool's value bit without its present bit) and its
        /// cells in the buffer, as the generated checks test them.
        /// </summary>
        private void CheckHeader(ObjectModel o, int start)
        {
            int words = o.HeaderWords;
            var used = new uint[words];
            var boolPresent = new uint[words];
            foreach (var c in o.Cells) used[c.Bit / 32] |= 1u << (c.Bit % 32);
            foreach (var b in o.Bools)
            {
                used[b.Bit / 32] |= 3u << (b.Bit % 32);
                boolPresent[b.Bit / 32] |= 1u << (b.Bit % 32);
            }

            var bad = new List<string>();
            for (int w = 0; w < words; w++)
            {
                if (~used[w] != 0) bad.Add($"(h{w} & 0x{~used[w]:X}u) != 0");
                if (boolPresent[w] != 0) bad.Add($"((h{w} >> 1) & ~h{w} & 0x{boolPresent[w]:X}u) != 0");
            }

            if (bad.Count == 0 && o.Cells.Count == 0) return;
            _w.Open("if (TC.Check)");
            if (bad.Count > 0) _w.Line($"if ({string.Join(" || ", bad)}) TesseraDeserializer.Fail();");
            if (o.Cells.Count > 0) _w.Line($"d.Range(ref p, {CellsBefore(o, int.MaxValue)});");
            _w.Close();
            _w.Line();
        }

        /// <summary>
        /// The checks of a list at <paramref name="vector"/> whose count is in <paramref name="count"/> (a uint), as the
        /// generated checks test them: its items in the buffer, bools 0 or 1, 8-byte numbers at a multiple of 8, and the
        /// references it holds counted.
        /// </summary>
        private void CheckItems(ValueModel e, string vector, string count)
        {
            int size = ItemSize(e);
            bool align8 = size >= 8 && e.Kind != WireKind.Struct && e.Kind != WireKind.Union;
            string flag(bool b) => b ? "true" : "false";
            if (e.IsNullableValueType)
            {
                _w.Line($"d.OptionalValues(ref {vector}, {count}, {size}, {flag(e.Kind == WireKind.Bool)}, {flag(align8)});");
            }
            else if (!WireFormat.IsReference(e.Kind))
            {
                _w.Line(size == 1 ? $"d.Range(ref {vector}, 4L + {count});" : $"d.Range(ref {vector}, 4 + {size}L * {count});");
                if (e.Kind == WireKind.Bool) _w.Line($"d.Booleans(ref Unsafe.Add(ref {vector}, 4), {count});");
                if (align8) _w.Line($"d.Aligned8(ref Unsafe.Add(ref {vector}, 4));");
            }
            else
            {
                _w.Line($"d.Range(ref {vector}, 4 + {(e.Kind == WireKind.Union ? 8 : 4)}L * {count});");
                _w.Line($"d.References({count});");
            }
        }

        private static int ItemSize(ValueModel e) => e.Kind == WireKind.Struct ? e.Struct!.Size : e.Kind == WireKind.Bool ? 1 : WireFormat.CellSize(e.Kind);

        // ------------------------------------------------------------------ abstract classes and interfaces

        private void EmitUnion(UnionModel u)
        {
            _w.Line();
            _w.Open($"public static {u.CsName} U{u.Index}<TC>(ref TesseraDeserializer d, ref byte cell, int depth) where TC : struct, ITesseraReadMode");
            _w.Line("ref byte slot = ref Unsafe.Add(ref cell, 4);");
            _w.Open("if (Unsafe.ReadUnaligned<uint>(ref slot) == 0)");
            _w.Line("if (TC.Check) TesseraDeserializer.Fail();   // a stored value needs its offset");
            _w.Line("return default;");
            _w.Close();
            _w.Line();
            _w.Open("switch (Unsafe.ReadUnaligned<uint>(ref cell))");
            foreach (var m in u.Members.OrderBy(m => m.Tag)) _w.Line($"case 0x{m.Tag:X8}u: return O{m.Type.Index}<TC>(ref d, ref d.Target<TC>(ref slot), depth);");
            _w.Line("default:");
            _w.Line("    if (TC.Check) TesseraDeserializer.Fail();");
            _w.Line("    return default;   // unchecked: a type this program does not know (written by another version of the classes)");
            _w.Close();
            _w.Close();
        }

        // ------------------------------------------------------------------ lists and dictionaries

        /// <summary>The method creating <paramref name="declared"/> from a stored list or dictionary, added on first use.</summary>
        private string Collection(TypeModel wire, ITypeSymbol declared)
        {
            string key = wire.Key + "|" + Cs(declared);
            if (!_collections.TryGetValue(key, out var c))
            {
                c = new Made
                {
                    Name = (wire is VectorModel ? "L" : "D") + _collections.Count.ToString(CultureInfo.InvariantCulture),
                    Id = _types.Count + _collections.Count,
                    Wire = wire,
                    Type = declared,
                };
                _collections[key] = c;
                _pending.Add(c);
            }

            return c.Name;
        }

        private void EmitCollection(Made c)
        {
            string type = Cs(c.Type);
            _w.Line();
            _w.Open($"public static {type} {c.Name}<TC>(ref TesseraDeserializer d, ref byte v, int depth) where TC : struct, ITesseraReadMode");
            _w.Line($"if (TC.Share && d.Find(ref v, {c.Id}) is {type} found) return found;");
            if (c.Wire is VectorModel vm)
            {
                Checked("d.Enter(depth);");   // its count is in the buffer when its offset passed the check
                EmitList(c, vm);
            }
            else EmitDictionary(c, (ObjectModel)c.Wire);
            _w.Close();
        }

        private void EmitList(Made c, VectorModel vm)
        {
            var e = vm.Element;
            var et = ElementOf(c.Type);
            string E = Cs(et);
            string type = Cs(c.Type);
            var shape = ListShape(c.Type, et, out string add, out IMethodSymbol? wrap);
            if (shape == Shape.None)
            {
                _w.Line($"throw new TesseraException({Naming.CsString($"Deserialize cannot create a {c.Type.ToDisplayString()}: give it a public constructor without parameters and an Add method, or a constructor that takes a list of its items.")});");
                return;
            }


            _w.Line("uint count = Unsafe.ReadUnaligned<uint>(ref v);");
            _w.Open("if (TC.Check)");
            CheckItems(e, "v", "count");
            _w.Close();
            _w.Line();
            _w.Line("int n = (int)count;");
            // Numbers, bools, chars, enums and plain structs: their bytes, copied as a block.
            bool block = !e.IsNullableValueType && (IsScalar(e.Kind) || (e.Kind == WireKind.Struct && e.Struct!.BlockCopy));
            // A plain struct's size is checked at run time: it guards against a layout the generator could not see.
            string? guard = e.Kind == WireKind.Struct ? $"Unsafe.SizeOf<{E}>() == {e.Struct!.Size}" : null;
            if (shape == Shape.Array)
            {
                if (block)
                {
                    string copy = $"return d.Keep<TC, {type}>(ref v, {c.Id}, TesseraReader.Span<{E}>(ref v).ToArray());";
                    if (guard == null)
                    {
                        _w.Line(copy);
                        return;
                    }

                    _w.Line($"if ({guard}) {copy}");
                }

                _w.Line($"var a = new {NewArray(E, "n")};");
                Items(e, et, "v", "a.Length", "depth + 1", x => $"a[i] = {x};");
                _w.Line($"return d.Keep<TC, {type}>(ref v, {c.Id}, a);");
                return;
            }

            string list = $"global::System.Collections.Generic.List<{E}>";
            _w.Line($"var list = new {list}(n);");
            if (shape == Shape.List || shape == Shape.Wrap)
            {
                _w.Line("global::System.Runtime.InteropServices.CollectionsMarshal.SetCount(list, n);");
                _w.Line("var items = global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan(list);");
                if (block && guard == null)
                {
                    _w.Line($"TesseraReader.Span<{E}>(ref v).CopyTo(items);");
                }
                else if (block)
                {
                    _w.Open($"if ({guard})");
                    _w.Line($"TesseraReader.Span<{E}>(ref v).CopyTo(items);");
                    _w.Close();
                    _w.Open("else");
                    Items(e, et, "v", "items.Length", "depth + 1", x => $"items[i] = {x};");
                    _w.Close();
                }
                else
                {
                    Items(e, et, "v", "items.Length", "depth + 1", x => $"items[i] = {x};");
                }

                if (shape == Shape.List)
                {
                    _w.Line($"return d.Keep<TC, {type}>(ref v, {c.Id}, list);");
                    return;
                }

                // A stack enumerates from its top, so it was stored top first: pushed back in the opposite order.
                string def = c.Type.OriginalDefinition.ToDisplayString();
                if (def == "System.Collections.Generic.Stack<T>" || def == "System.Collections.Concurrent.ConcurrentStack<T>") _w.Line("list.Reverse();");
                _w.Line($"return d.Keep<TC, {type}>(ref v, {c.Id}, new {type}(list));");
                return;
            }

            _w.Line($"var c = new {type}();");
            Items(e, et, "v", "n", "depth + 1", x => $"{add}({x});");
            _w.Line($"return d.Keep<TC, {type}>(ref v, {c.Id}, c);");
        }

        private void EmitDictionary(Made c, ObjectModel map)
        {
            var keysMember = map.Members.Single(m => m.WireName == "Keys");
            var valuesMember = map.Members.Single(m => m.WireName == "Values");
            int keysAt = 4 + map.Cells.Where(x => x.Bit < keysMember.Bit).Sum(x => x.CellSize);
            int valuesAt = 4 + map.Cells.Where(x => x.Bit < valuesMember.Bit).Sum(x => x.CellSize);
            var (kt, vt) = DictionaryArgs(c.Type);
            string K = Cs(kt), V = Cs(vt), type = Cs(c.Type);
            string dictionary = $"global::System.Collections.Generic.Dictionary<{K}, {V}>";
            var dictionarySymbol = _compilation.GetTypeByMetadataName("System.Collections.Generic.Dictionary`2")!.Construct(kt, vt);
            string create, store;
            bool wrap = false;
            if (SymbolEqualityComparer.Default.Equals(c.Type.OriginalDefinition, dictionarySymbol.OriginalDefinition) ||
                (c.Type.TypeKind == TypeKind.Interface && _compilation.HasImplicitConversion(dictionarySymbol, c.Type)))
            {
                create = $"new {dictionary}(n)";
                store = "c";
            }
            else if (c.Type is INamedTypeSymbol named && !named.IsAbstract && named.TypeKind == TypeKind.Class &&
                     named.InstanceConstructors.Any(x => x.Parameters.Length == 0 && Accessible(x)) &&
                     named.AllInterfaces.Any(i => i.OriginalDefinition.ToDisplayString() == "System.Collections.Generic.IDictionary<TKey, TValue>"))
            {
                create = $"new {type}()";
                store = $"((global::System.Collections.Generic.IDictionary<{K}, {V}>)c)";
            }
            else if (c.Type is INamedTypeSymbol wrapped && !wrapped.IsAbstract && wrapped.TypeKind == TypeKind.Class &&
                     wrapped.InstanceConstructors.Any(x => x.Parameters.Length == 1 && Accessible(x) && _compilation.HasImplicitConversion(dictionarySymbol, x.Parameters[0].Type)))
            {
                create = $"new {dictionary}(n)";
                store = "c";
                wrap = true;
            }
            else
            {
                _w.Line($"throw new TesseraException({Naming.CsString($"Deserialize cannot create a {c.Type.ToDisplayString()}: give it a public constructor without parameters, or one that takes a dictionary.")});");
                return;
            }

            // Both lists are always stored, and nothing else.
            uint both = map.Cells.Aggregate(0u, (m, x) => m | 1u << x.Bit);
            Checked("d.Enter(depth);", "d.Range(ref v, 12);", $"if (Unsafe.ReadUnaligned<uint>(ref v) != 0x{both:X}u) TesseraDeserializer.Fail();");
            _w.Line($"ref byte keys = ref d.Target<TC>(ref Unsafe.Add(ref v, {keysAt}));");
            _w.Line($"ref byte values = ref d.Target<TC>(ref Unsafe.Add(ref v, {valuesAt}));");
            _w.Open("if (TC.Check)");
            foreach (var (list, element) in new[] { ("keys", map.Map!.Key), ("values", map.Map.Value) })
            {
                _w.Line("d.Enter(depth + 1);");
                CheckItems(element, list, $"Unsafe.ReadUnaligned<uint>(ref {list})");
            }

            // Lists of different lengths are read by the separate check (a version of the classes whose values changed).
            _w.Line("if (Unsafe.ReadUnaligned<uint>(ref keys) != Unsafe.ReadUnaligned<uint>(ref values)) TesseraDeserializer.Fail();");
            _w.Close();
            _w.Line();
            _w.Line("int n = (int)Unsafe.ReadUnaligned<uint>(ref keys);");
            _w.Line("int stored = (int)Unsafe.ReadUnaligned<uint>(ref values);");
            _w.Line("if (stored < n) n = stored;   // values of a type that changed (another version of the classes) cannot be read");
            _w.Line($"var c = {create};");
            var key = map.Map!.Key;
            Items(map.Map.Value, vt, "values", "n", "depth + 2", x => $"{store}[{(key.Kind == WireKind.String ? "k" : KeyRead(key, K))}] = {x};",
                key.Kind == WireKind.String ? new[]
                {
                    "ref byte ks = ref Unsafe.Add(ref keys, 4 + 4 * i);",
                    "if (Unsafe.ReadUnaligned<uint>(ref ks) == 0) continue;",
                    "string k = d.String<TC>(ref d.Target<TC>(ref ks));",
                } : null);
            _w.Line(wrap ? $"return d.Keep<TC, {type}>(ref v, {c.Id}, new {type}(c));" : $"return d.Keep<TC, {type}>(ref v, {c.Id}, c);");
        }

        private static string KeyRead(ValueModel key, string K)
        {
            int size = WireFormat.CellSize(key.Kind);
            return $"Unsafe.ReadUnaligned<{K}>(ref Unsafe.Add(ref keys, 4 + {size} * i))";
        }

        /// <summary>
        /// A loop over the items of the list at <paramref name="vector"/> (a <c>ref byte</c> local), <paramref name="count"/>
        /// of them, storing each with <paramref name="store"/>; <paramref name="first"/> starts each iteration.
        /// </summary>
        private void Items(ValueModel e, ITypeSymbol et, string vector, string count, string depth, Func<string, string> store, string[]? first = null)
        {
            if (e.IsNullableValueType)
            {
                // Optional values: a presence bit per item, then every item's value.
                _w.Line($"int at = 4 + 4 * (((int)Unsafe.ReadUnaligned<uint>(ref {vector}) + 31) >> 5);");
            }

            _w.Open($"for (int i = 0; i < {count}; i++)");
            if (first != null)
            {
                foreach (var line in first) _w.Line(line);
            }

            int size = e.Kind == WireKind.Struct ? e.Struct!.Size : e.Kind == WireKind.Bool ? 1 : WireFormat.CellSize(e.Kind);
            string nullable = e.Kind == WireKind.Struct ? e.Struct!.CsName + "?" : e.IsNullableValueType ? Scalar(e) + "?" : "";
            if (e.IsNullableValueType)
            {
                string value = e.Kind == WireKind.Struct
                    ? StructRead(e.Struct!, $"ref Unsafe.Add(ref {vector}, at + {size} * i)")
                    : $"Unsafe.ReadUnaligned<{Scalar(e)}>(ref Unsafe.Add(ref {vector}, at + {size} * i))";
                _w.Line(store($"((Unsafe.ReadUnaligned<uint>(ref Unsafe.Add(ref {vector}, 4 + 4 * (i >> 5))) >> (i & 31)) & 1u) != 0 ? ({nullable}){value} : null"));
            }
            else if (e.Kind == WireKind.Union)
            {
                // A null item has no offset.
                _w.Line($"ref byte s = ref Unsafe.Add(ref {vector}, 4 + 8 * i);");
                _w.Line(store($"Unsafe.ReadUnaligned<uint>(ref Unsafe.Add(ref s, 4)) == 0 ? default : U{e.Union!.Index}<TC>(ref d, ref s, {depth})"));
            }
            else if (WireFormat.IsReference(e.Kind))
            {
                _w.Line($"ref byte s = ref Unsafe.Add(ref {vector}, 4 + 4 * i);");
                string read = e.Kind switch
                {
                    WireKind.String => "d.String<TC>(ref d.Target<TC>(ref s))",
                    WireKind.Object when e.Object!.Map != null => $"{Collection(e.Object, et)}<TC>(ref d, ref d.Target<TC>(ref s), {depth})",
                    WireKind.Object => $"O{e.Object.Index}<TC>(ref d, ref d.Target<TC>(ref s), {depth})",
                    WireKind.Vector => $"{Collection(e.Vector!, et)}<TC>(ref d, ref d.Target<TC>(ref s), {depth})",
                    _ => StructRead(e.Struct!, $"ref d.SharedStruct<TC>(ref s, {e.Struct!.Size})"),
                };
                _w.Line(store($"Unsafe.ReadUnaligned<uint>(ref s) == 0 ? default : {read}"));
            }
            else if (e.Kind == WireKind.Struct)
            {
                _w.Line(store(StructRead(e.Struct!, $"ref Unsafe.Add(ref {vector}, 4 + {size} * i)")));
            }
            else
            {
                _w.Line(store($"Unsafe.ReadUnaligned<{Scalar(e)}>(ref Unsafe.Add(ref {vector}, 4 + {size} * i))"));
            }

            _w.Close();
        }

        /// <summary>How a list of <paramref name="element"/> is created as <paramref name="type"/>.</summary>
        private Shape ListShape(ITypeSymbol type, ITypeSymbol element, out string add, out IMethodSymbol? wrap)
        {
            add = "c.Add";
            wrap = null;
            if (type is IArrayTypeSymbol) return Shape.Array;
            var list = _compilation.GetTypeByMetadataName("System.Collections.Generic.List`1")!.Construct(element);
            if (SymbolEqualityComparer.Default.Equals(type.OriginalDefinition, list.OriginalDefinition)) return Shape.List;
            if (type.TypeKind == TypeKind.Interface && _compilation.HasImplicitConversion(list, type)) return Shape.List;
            if (type is not INamedTypeSymbol named || named.IsAbstract || named.TypeKind != TypeKind.Class) return Shape.None;
            if (named.InstanceConstructors.Any(c => c.Parameters.Length == 0 && Accessible(c)))
            {
                for (var t = named; t != null; t = t.BaseType)
                {
                    if (t.GetMembers("Add").OfType<IMethodSymbol>().Any(m => !m.IsStatic && m.Parameters.Length == 1 && Accessible(m) &&
                                                                             SymbolEqualityComparer.Default.Equals(m.Parameters[0].Type, element)))
                    {
                        return Shape.Add;
                    }
                }

                if (named.AllInterfaces.Any(i => i.OriginalDefinition.ToDisplayString() == "System.Collections.Generic.ICollection<T>" &&
                                                 SymbolEqualityComparer.Default.Equals(i.TypeArguments[0], element)))
                {
                    add = $"((global::System.Collections.Generic.ICollection<{Cs(element)}>)c).Add";
                    return Shape.Add;
                }
            }

            wrap = named.InstanceConstructors.FirstOrDefault(c => c.Parameters.Length == 1 && Accessible(c) && _compilation.HasImplicitConversion(list, c.Parameters[0].Type));
            return wrap != null ? Shape.Wrap : Shape.None;
        }

        /// <summary>The items' type of a list type: its element type, or the T of the IEnumerable&lt;T&gt; it is or implements.</summary>
        private static ITypeSymbol ElementOf(ITypeSymbol type)
        {
            if (type is IArrayTypeSymbol array) return array.ElementType;
            var named = (INamedTypeSymbol)type;
            foreach (var i in (named.TypeKind == TypeKind.Interface ? new[] { named } : Array.Empty<INamedTypeSymbol>()).Concat(named.AllInterfaces))
            {
                if (i.OriginalDefinition.SpecialType == SpecialType.System_Collections_Generic_IEnumerable_T) return i.TypeArguments[0];
            }

            throw new InvalidOperationException("not a list: " + type);
        }

        /// <summary>The key and value types of a dictionary type.</summary>
        private static (ITypeSymbol Key, ITypeSymbol Value) DictionaryArgs(ITypeSymbol type)
        {
            var named = (INamedTypeSymbol)type;
            foreach (var i in new[] { named }.Concat(named.AllInterfaces))
            {
                string def = i.OriginalDefinition.ToDisplayString();
                if (def == "System.Collections.Generic.IDictionary<TKey, TValue>" || def == "System.Collections.Generic.IReadOnlyDictionary<TKey, TValue>")
                {
                    return (i.TypeArguments[0], i.TypeArguments[1]);
                }
            }

            throw new InvalidOperationException("not a dictionary: " + type);
        }

        /// <summary>An array creation of <paramref name="n"/> items of type <paramref name="element"/> (jagged: <c>int[n][]</c>).</summary>
        private static string NewArray(string element, string n)
        {
            int end = element.Length;
            while (end >= 2 && element[end - 1] == ']' && element[end - 2] == '[') end -= 2;
            return element.Substring(0, end) + "[" + n + "]" + element.Substring(end);
        }

        // ------------------------------------------------------------------ helpers

        private static ITypeSymbol MemberType(MemberModel m) => m.Symbol switch
        {
            IFieldSymbol f => f.Type,
            IPropertySymbol p => p.Type,
            _ => throw new InvalidOperationException("not a field or property: " + m.Symbol),
        };

        /// <summary>Whether generated code in this project can use the symbol (as the writer's members, by accessibility).</summary>
        private bool Accessible(ISymbol symbol)
        {
            switch (symbol.DeclaredAccessibility)
            {
                case Accessibility.Public:
                    return true;
                case Accessibility.Internal:
                case Accessibility.ProtectedOrInternal:
                    return SymbolEqualityComparer.Default.Equals(symbol.ContainingAssembly, _compilation.Assembly);
                default:
                    return false;
            }
        }

        private static string Cs(ITypeSymbol t) => t.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        private static bool IsScalar(WireKind k) => k >= WireKind.Bool && k <= WireKind.Char16;

        /// <summary>The C# type of a number, bool, char or enum.</summary>
        private static string Scalar(ValueModel v)
        {
            if (v.Enum != null) return v.Enum.CsName;
            switch (v.Kind)
            {
                case WireKind.Bool: return "bool";
                case WireKind.Int8: return "sbyte";
                case WireKind.UInt8: return "byte";
                case WireKind.Int16: return "short";
                case WireKind.UInt16: return "ushort";
                case WireKind.Char16: return "char";
                case WireKind.Int32: return "int";
                case WireKind.UInt32: return "uint";
                case WireKind.Int64: return "long";
                case WireKind.UInt64: return "ulong";
                case WireKind.Float32: return "float";
                case WireKind.Float64: return "double";
                default: throw new InvalidOperationException("not a scalar: " + v.Kind);
            }
        }

        private static string Ident(string name) =>
            SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None || SyntaxFacts.GetContextualKeywordKind(name) == SyntaxKind.UnderscoreToken ? "@" + name : name;
    }
